/* Relational operators */
#include<iostream>
using namespace std;
int main()
{
	int a,b;
	cout<<"Enter number1:";
    cin>>a;
    cout<<"Enter number2:";
    cin>>b;
    cout<< "\n a > b  = " << (a > b);
    cout<< "\n a < b  = " << (a < b);
    cout<< "\n a >= b = " << (a >= b);
    cout<< "\n a <= b = " << (a <= b);
    cout<< "\n a == b = " << (a == b);
    cout<< "\n a != b = " << (a != b);
	return 0;	
}
